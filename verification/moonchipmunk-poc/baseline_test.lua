package.path = './?.lua;' .. package.path
local B=require('baseline')
local w=B.new()
assert(#w:snapshot()==8)
local before=w:snapshot()
w:step(.05,{{throttle=1,steer=.2}})
local after=w:snapshot()
assert(after[1].vx~=before[1].vx)
local other=B.new()
assert(other:snapshot()[1].vx==0)
w:set_car(1,{x=-2,y=0,vx=3,vy=0,angular_velocity=0})
w:set_car(2,{x=2,y=0,vx=-3,vy=0,angular_velocity=0})
for i=1,30 do w:step(.05,{}) end
assert(w.collision_count>0)
local p=w:snapshot()
assert(p[1].vx<0 and p[2].vx>0)
w:close();w:close();other:close()
assert(not pcall(function() w:step(.05,{}) end))
print('BASELINE_ASSERTIONS_PASS')
